    public void addEvent(Long ipa, String email) {

        if (event.isAllDay()) {
            //see https://github.com/primefaces/primefaces/issues/1164
            if (event.getStartDate().toLocalDate().equals(event.getEndDate().toLocalDate())) {
                event.setEndDate(event.getEndDate().plusDays(1));
            }
        }

        if (event.getId() == null) {
            eventModel.addEvent(event);
        } else {
            eventModel.updateEvent(event);
        }                       
        
        String[] ipaArr = event.getDescription().split(":");
        
        selected.setIPA(Long.parseLong(ipaArr[0]));
        selected.setEventDescription("Schedule: " + ipaArr[1]);
        selected.setEventId(event.getId());
        selected.setPeriodFrom(Date.from(event.getStartDate().toLocalDate().atStartOfDay().toInstant(ZoneOffset.UTC)));
        selected.setPeriodTo(Date.from(event.getStartDate().toLocalDate().atStartOfDay().toInstant(ZoneOffset.UTC)));
        selected.setEventTitle(event.getTitle());

        create(Long.parseLong(ipaArr[0]));

        event = new DefaultScheduleEvent();

    }

